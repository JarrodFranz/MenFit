import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';

/// Guard tests for the config surface the transition chime needs (ADR 014).
///
/// None of this is exercised by a widget test — a missing `assets/audio/`
/// entry, or a caret constraint that lets a plugin float, fails on a device
/// or in a Gradle configuration phase, hours after the change that caused
/// it. Same pitfall class as `ocr_platform_config_guard_test.dart`.
void main() {
  final pubspec = File('pubspec.yaml').readAsLinesSync();

  group('pubspec.yaml', () {
    test('declares the assets/audio/ directory', () {
      // Without this line the chime is simply not in the bundle and
      // `AssetSource` fails at runtime on every platform - silently, since
      // the player swallows its failures.
      expect(
        pubspec.map((l) => l.trim()),
        contains('- assets/audio/'),
        reason:
            'assets/audio/transition_chime.wav must be declared under '
            'flutter: assets: or it is not bundled.',
      );
    });

    test('pins audioplayers and wakelock_plus to exact versions', () {
      // Exact pins, not carets: both plugins carry native Android build
      // logic whose interaction with this repo's AGP 9.0.1 +
      // `android.builtInKotlin=false` combination was verified by building,
      // not by reading (knowledge/troubleshooting/android_build.md). A
      // caret would let a future `pub get` change that native code without
      // anyone rebuilding the APK.
      for (final pin in ['audioplayers: 6.8.1', 'wakelock_plus: 1.8.0']) {
        expect(
          pubspec.map((l) => l.trim()),
          contains(pin),
          reason:
              'exact pin required; a caret here changes native Android '
              'build logic on an unrelated `pub get`.',
        );
      }
    });
  });

  group('assets/audio/transition_chime.wav', () {
    final file = File('assets/audio/transition_chime.wav');

    test('exists', () {
      expect(
        file.existsSync(),
        isTrue,
        reason:
            'Generated by scripts/gen_transition_chime.py - it is our own '
            'synthesized asset, not a third-party sound file.',
      );
    });

    test('is 16-bit mono PCM at 44.1 kHz, and about 1.6 s long', () {
      // Read straight out of the RIFF header. The point is not pedantry
      // about the format: it is that if someone ever replaces this with a
      // downloaded sample, the numbers change and the licence question
      // (which the generator script exists to answer) comes back.
      final bytes = file.readAsBytesSync();
      final data = ByteData.sublistView(Uint8List.fromList(bytes));

      expect(String.fromCharCodes(bytes.sublist(0, 4)), 'RIFF');
      expect(String.fromCharCodes(bytes.sublist(8, 12)), 'WAVE');

      expect(data.getUint16(20, Endian.little), 1, reason: 'PCM format tag');
      expect(data.getUint16(22, Endian.little), 1, reason: 'mono');
      expect(data.getUint32(24, Endian.little), 44100, reason: 'sample rate');
      expect(data.getUint16(34, Endian.little), 16, reason: 'bits per sample');

      final frames = data.getUint32(40, Endian.little) ~/ 2;
      expect(
        frames / 44100.0,
        closeTo(1.6, 0.05),
        reason:
            'a cue longer than about two seconds overlaps the next pose; '
            'shorter than about one and it reads as a notification blip.',
      );
    });
  });

  test('scripts/gen_transition_chime.py is committed beside the asset', () {
    // The asset is only licence-free because we can point at the thing that
    // made it. Deleting the generator as "unused tooling" quietly turns a
    // provable provenance into an unprovable one.
    final script = File('scripts/gen_transition_chime.py');
    expect(script.existsSync(), isTrue);
    expect(
      script.readAsStringSync(),
      contains('GENERATED BY THIS SCRIPT'),
      reason:
          'the header has to say plainly that the asset is not '
          'third-party.',
    );
  });
}
