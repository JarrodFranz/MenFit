#!/usr/bin/env python3
"""Generates assets/audio/transition_chime.wav.

The chime shipped with the app is GENERATED BY THIS SCRIPT, not a
third-party sound file. There is no licence to honour and no attribution to
carry, because nobody else made it: it is four decaying sine partials in a
2:1:3:4 ratio over a 528 Hz fundamental, which is the crude but recognisable
shape of a struck singing bowl. Regenerating it from here is the only
supported way to change it - do not drop a downloaded sample in its place
without an evaluation of where that sample came from.

Run:  python scripts/gen_transition_chime.py
Out:  assets/audio/transition_chime.wav  (16-bit PCM, mono, 44.1 kHz, 1.6 s)

Standard library only (`wave` + `struct` + `math`), so it needs no
environment beyond a Python 3 interpreter.
"""

from __future__ import annotations

import math
import struct
import wave
from pathlib import Path

SAMPLE_RATE = 44_100
DURATION_SECONDS = 1.6

# (frequency Hz, amplitude, exponential decay time constant in seconds).
# Higher partials are quieter and die sooner, which is what makes the tail
# read as a bowl rather than an organ.
PARTIALS: list[tuple[float, float, float]] = [
    (528.0, 1.00, 1.8),
    (1056.0, 0.35, 1.2),
    (1584.0, 0.15, 0.9),
    (2112.0, 0.06, 0.6),
]

ATTACK_SECONDS = 0.020
"""Without a short attack the first sample is a step from silence to full
amplitude, which every speaker reproduces as a click in front of the note."""

FADE_OUT_SECONDS = 0.3
"""The exponential tail is still audible at 1.6 s; cutting it dead would put
a second click at the end."""

PEAK = 0.42
"""Headroom on purpose. This plays over her own music at whatever volume she
already chose - a cue that startles is a worse cue."""

OUTPUT_PATH = Path(__file__).resolve().parent.parent / "assets" / "audio" / "transition_chime.wav"


def render() -> list[float]:
    """Renders the chime as floats in roughly [-1, 1], peak-normalised."""
    total_samples = int(SAMPLE_RATE * DURATION_SECONDS)
    attack_samples = int(SAMPLE_RATE * ATTACK_SECONDS)
    fade_start = total_samples - int(SAMPLE_RATE * FADE_OUT_SECONDS)

    samples: list[float] = []
    for i in range(total_samples):
        t = i / SAMPLE_RATE
        value = 0.0
        for frequency, amplitude, decay in PARTIALS:
            value += amplitude * math.sin(2.0 * math.pi * frequency * t) * math.exp(-t / decay)

        if i < attack_samples:
            value *= i / attack_samples
        if i >= fade_start:
            value *= (total_samples - i) / (total_samples - fade_start)

        samples.append(value)

    loudest = max(abs(s) for s in samples) or 1.0
    scale = PEAK / loudest
    return [s * scale for s in samples]


def main() -> None:
    samples = render()
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    frames = b"".join(
        struct.pack("<h", max(-32768, min(32767, int(round(s * 32767.0))))) for s in samples
    )

    with wave.open(str(OUTPUT_PATH), "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(SAMPLE_RATE)
        out.writeframes(frames)

    print(f"wrote {OUTPUT_PATH} ({len(frames) + 44} bytes)")


if __name__ == "__main__":
    main()
